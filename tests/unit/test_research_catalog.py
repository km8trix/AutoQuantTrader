D = Decimal


class MemoryObjects:
    def __init__(self):
        self.payloads = {}
        self.reads = []

    def put(self, payload, *, codec_version="personal-record/1", max_bytes=MAX_INPUT_BYTES):
        assert len(payload) <= max_bytes
        digest = hashlib.sha256(payload).hexdigest()
        self.payloads[digest] = payload
        return ObjectRef(digest, len(payload), codec_version)

    def read(self, reference, *, max_bytes=MAX_INPUT_BYTES):
        self.reads.append((reference, max_bytes))
        return self.payloads[reference.object_sha256]


def catalog(source, objects, *, archive=None):
    return create_catalog_entry(
        display_name="transparent catalog test",
        source=source,
        prior_access=protocol_for(source).prior_access,
        source_inputs=objects.put(encode_record(source)),
        archive=archive,
        settlement_calendar=objects.put(
            encode_record(source.spec.execution_policy.settlement_calendar)
        ),
    )


def ordinary(entry, source, *, cost=COST_SCENARIOS[0]):
    days = tuple(s.session_label for s in source.spec.calendar.sessions)
    return prepare_catalog_run_inputs(
        entry=entry,
        source=source,
        configuration=ReferenceConfiguration("buy_hold", 2),
        evaluation=EvaluationSpec(
            "ordinary", days[:2], days[2:6], f"retrospective-{entry.prior_access.status}"
        ),
        initial_cash=D(10000),
        cost=cost,
        current_build_pins=source.spec.pins,
    )


